package online.mtradius.mtping;

import android.os.SystemClock;
import org.json.JSONArray;
import org.json.JSONObject;
import java.io.InputStream;
import java.net.HttpURLConnection;
import java.net.URL;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.concurrent.atomic.AtomicLong;
import okhttp3.OkHttpClient;
import okhttp3.Request;
import okhttp3.Response;
import okhttp3.WebSocket;
import okhttp3.WebSocketListener;
import okio.ByteString;

/**
 * Independent open-protocol throughput validation against M-Lab NDT7.
 * The Locate v2 API supplies signed server URLs; never invent server names.
 * M-Lab is a single-flow estimate, not Ookla's multi-flow Speedtest.
 */
final class MlabNdt7 {
    static final class Result {
        double download=-1,upload=-1;
        String server="—";
    }
    private final AtomicBoolean cancelled;
    private final OkHttpClient client=new OkHttpClient.Builder()
            .connectTimeout(6,TimeUnit.SECONDS)
            .readTimeout(0,TimeUnit.MILLISECONDS)
            .build();
    private volatile WebSocket active;
    MlabNdt7(AtomicBoolean cancelled){this.cancelled=cancelled;}
    void cancel(){WebSocket s=active;if(s!=null)s.cancel();}
    private void check() throws InterruptedException {
        if(cancelled.get()||Thread.currentThread().isInterrupted())throw new InterruptedException();
    }
    private String[] locate() throws InterruptedException {
        check();HttpURLConnection conn=null;
        try{
            conn=(HttpURLConnection)new URL("https://locate.measurementlab.net/v2/nearest/ndt/ndt7")
                    .openConnection();
            conn.setConnectTimeout(5000);conn.setReadTimeout(5000);
            conn.setRequestProperty("User-Agent","MT_TOOLS/6.4.0 Android-NDT7");
            if(conn.getResponseCode()!=200)return null;
            StringBuilder json=new StringBuilder();
            try(InputStream input=conn.getInputStream()){
                byte[] b=new byte[4096];int n;
                while((n=input.read(b))!=-1&&json.length()<32000)
                    json.append(new String(b,0,n,java.nio.charset.StandardCharsets.UTF_8));
            }
            JSONArray servers=new JSONObject(json.toString()).optJSONArray("results");
            if(servers==null)return null;
            for(int i=0;i<servers.length();i++){
                JSONObject row=servers.optJSONObject(i);
                if(row==null)continue;
                JSONObject urls=row.optJSONObject("urls");
                if(urls==null)continue;
                String down=urls.optString("wss:///ndt/v7/download","");
                String up=urls.optString("wss:///ndt/v7/upload","");
                // Only signed WSS URLs generated by the official discovery service.
                if(down.startsWith("wss://")&&up.startsWith("wss://")
                        &&down.contains(".measurement-lab.org/")
                        &&up.contains(".measurement-lab.org/"))
                    return new String[]{down,up,row.optString("machine","M-Lab")};
            }
        }catch(Exception ignored){
            // M-Lab may have no capacity or be unavailable in a region.
        }finally{if(conn!=null)conn.disconnect();}
        return null;
    }

    private double test(String url,boolean upload)throws InterruptedException {
        check();
        final AtomicLong bytes=new AtomicLong();
        final AtomicLong remoteBytes=new AtomicLong();
        final AtomicLong remoteElapsed=new AtomicLong();
        final AtomicLong started=new AtomicLong();
        final CountDownLatch finished=new CountDownLatch(1);
        Request request=new Request.Builder().url(url)
                .header("Sec-WebSocket-Protocol","net.measurementlab.ndt.v7")
                .header("User-Agent","MT_TOOLS/6.4.0 Android-NDT7").build();
        WebSocketListener listener=new WebSocketListener(){
            @Override public void onOpen(WebSocket ws,Response response) {
                started.set(SystemClock.elapsedRealtimeNanos());
                if(!upload)return;
                Thread sender=new Thread(()->{
                    byte[] payload=new byte[16384];
                    new java.security.SecureRandom().nextBytes(payload);
                    ByteString chunk=ByteString.of(payload,0,payload.length);
                    long until=SystemClock.elapsedRealtime()+9700;
                    try{
                        while(!cancelled.get()&&finished.getCount()>0&&
                                SystemClock.elapsedRealtime()<until){
                            if(ws.queueSize()<512*1024){
                                if(!ws.send(chunk))break;
                            }else Thread.sleep(7);
                        }
                    }catch(InterruptedException ex){
                        Thread.currentThread().interrupt();
                    }
                },"ndt7-upload");sender.setDaemon(true);sender.start();
            }
            @Override public void onMessage(WebSocket ws,ByteString payload){
                if(!upload)bytes.addAndGet(payload.size());
            }
            @Override public void onMessage(WebSocket ws,String value){
                try{
                    JSONObject app=new JSONObject(value).optJSONObject("AppInfo");
                    if(app!=null){
                        long received=app.optLong("NumBytes",0);
                        long micros=app.optLong("ElapsedTime",0);
                        if(received>0&&micros>0){
                            remoteBytes.set(received);remoteElapsed.set(micros);
                        }
                    }
                }catch(Exception ignored){}
            }
            @Override public void onClosed(WebSocket ws,int code,String reason){finished.countDown();}
            @Override public void onClosing(WebSocket ws,int code,String reason){
                ws.close(code,null);finished.countDown();
            }
            @Override public void onFailure(WebSocket ws,Throwable ex,Response response){
                finished.countDown();
            }
        };
        WebSocket socket=client.newWebSocket(request,listener);
        active=socket;
        long waitEnd=SystemClock.elapsedRealtime()+14500;
        try{
            while(SystemClock.elapsedRealtime()<waitEnd&&finished.getCount()>0){
                check();finished.await(80,TimeUnit.MILLISECONDS);
            }
        }finally{
            socket.cancel();
            active=null;
        }
        double elapsed=started.get()==0?-1:(SystemClock.elapsedRealtimeNanos()-started.get())/1e9;
        if(remoteBytes.get()>0&&remoteElapsed.get()>0){
            return remoteBytes.get()*8.0/remoteElapsed.get()/1.0; // microseconds -> Mbps
        }
        // Download is reliably counted on the client; upload must be confirmed
        // by server rather than counting queued WebSocket writes as delivered.
        if(upload || elapsed<2 || bytes.get()<128*1024)return -1;
        return bytes.get()*8/elapsed/1e6;
    }
    Result run() throws InterruptedException {
        Result result=new Result();
        String[] server=locate();
        if(server==null)return result;
        result.server=server[2];
        try{
            result.download=test(server[0],false);
            check();
            result.upload=test(server[1],true);
        }finally{client.dispatcher().executorService().shutdown();}
        return result;
    }
}
